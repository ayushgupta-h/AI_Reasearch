"""Unit tests for backend/report_cleaner.py."""

from report_cleaner import clean_report_markdown, extract_frontmatter_dict


def test_clean_report_strips_fenced_yaml():
    raw = (
        "---\n"
        'title: "Quantum Computing"\n'
        'generated_at: "2026-11-16T20:00:00"\n'
        'provider: "gemini"\n'
        "critic_score: 9/10\n"
        "---\n\n"
        "# Quantum Computing Overview\n\n"
        "Quantum computing harnesses the phenomena of quantum mechanics.\n"
    )
    cleaned = clean_report_markdown(raw)
    assert "title:" not in cleaned
    assert "generated_at:" not in cleaned
    assert "critic_score:" not in cleaned
    assert "# Quantum Computing Overview" in cleaned
    assert "Quantum computing harnesses" in cleaned


def test_clean_report_strips_unfenced_loose_metadata_and_duplicates():
    raw = (
        'title: "Nvidia Corporation" generated_at: "2026-11-16" provider: "gemini"\n'
        "critic_score: 6/10 revisions: 2\n"
        "# Nvidia Corporation\n"
        "Nvidia Corporation\n"
        'title: "Nvidia Corporation" generated_at: "2026-11-17" provider: "expert"\n'
        "## Executive Summary\n\n"
        "Nvidia recorded revenue of $215.9 billion.\n"
    )
    cleaned = clean_report_markdown(raw)
    assert "title:" not in cleaned
    assert "generated_at:" not in cleaned
    assert "revisions:" not in cleaned
    assert "## Executive Summary" in cleaned
    assert "$215.9 billion" in cleaned


def test_clean_report_strips_debug_appendixes():
    raw = (
        "# Clean Document Title\n\n"
        "Valid report text.\n\n"
        "## Citation Validation Appendix\n"
        "Auto-generated by ResearchAI\n"
        "1/4 sources live\n"
        "# Domain Status HTTP URL\n"
        "1 www.nvidia.com Live 200\n\n"
        "Source Credibility Assessment\n"
        "Heuristic assessment table..."
    )
    cleaned = clean_report_markdown(raw)
    assert "Valid report text." in cleaned
    assert "Citation Validation Appendix" not in cleaned
    assert "Auto-generated by ResearchAI" not in cleaned
    assert "Source Credibility Assessment" not in cleaned


def test_extract_frontmatter_dict():
    raw = (
        "---\n"
        'title: "AI In Medicine"\n'
        'provider: "groq"\n'
        "---\n\n"
        "# AI In Medicine\n\n"
        "Content..."
    )
    meta, body = extract_frontmatter_dict(raw)
    assert meta.get("title") == "AI In Medicine"
    assert meta.get("provider") == "groq"
    assert "# AI In Medicine" in body
